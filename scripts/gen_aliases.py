#!/usr/bin/env python3
"""Regenerate src/aliases.odin from public declarations in ecs/.

Run from the repo root:
    python3 scripts/gen_aliases.py
"""
import re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
ECS = ROOT / "ecs"
OUT = ROOT / "src" / "aliases.odin"

public = set()
for path in sorted(ECS.glob("*.odin")):
    lines = path.read_text().splitlines()
    prev_private = False
    for i, line in enumerate(lines):
        m = re.match(r'^([A-Za-z_][A-Za-z0-9_]*)\s*::', line)
        if m:
            name = m.group(1)
            # private if the immediately preceding non-empty line is @(private)
            j = i - 1
            while j >= 0 and lines[j].strip() == "":
                j -= 1
            if j >= 0 and lines[j].strip() == "@(private)":
                continue
            public.add(name)

public = sorted(public)

body = [
    "package shoal",
    "",
    'import ecs "../ecs"',
    "",
    "// auto-generated by scripts/gen_aliases.py — do not edit by hand.",
    "// re-exports the public ecs core API so engine code (and external",
    "// callers importing src/ as `ecs`) can use the unqualified names.",
    "",
]
for name in public:
    body.append(f"{name} :: ecs.{name}")
body.append("")

OUT.write_text("\n".join(body))
print(f"wrote {OUT} ({len(public)} aliases)")

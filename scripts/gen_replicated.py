#!/usr/bin/env python3
"""Generate serialize/deserialize procs for Odin structs tagged // @replicated.

Usage:
    python3 scripts/gen_replicated.py <input.odin> [output.odin]

Scans <input.odin> for structs preceded by a `// @replicated` comment and
generates serialize_<name> / deserialize_<name> procs plus a
register_replicated_components() helper. Output is meant to live in the same
package as the structs so the generated procs can reference them directly.

Supported field types: i8 u8 i16 u16 i32 u32 i64 u64 f32 f64 bool
                      rl.Vector2 rl.Vector3 rl.Color
"""
import re, sys, pathlib

TYPE_SIZES = {
    'i8':1,'u8':1,'i16':2,'u16':2,'i32':4,'u32':4,'i64':8,'u64':8,
    'f32':4,'f64':8,'bool':1,
}
RL_FIELDS = {
    'rl.Vector2': [('x','f32'),('y','f32')],
    'rl.Vector3': [('x','f32'),('y','f32'),('z','f32')],
    'rl.Color':   [('r','u8'),('g','u8'),('b','u8'),('a','u8')],
}

def parse_structs(text):
    # find // @replicated followed by Name :: struct { ... }
    structs = []
    # regex: @replicated comment, then Name :: struct { fields }
    pattern = re.compile(r'//\s*@replicated\s*\n(\w+)\s*::\s*struct\s*\{\s*(.*?)\s*\}', re.S)
    for m in pattern.finditer(text):
        name = m.group(1)
        body = m.group(2)
        fields = []
        for line in body.splitlines():
            line = line.strip().rstrip(',')
            if not line or line.startswith('//'):
                continue
            if ':' not in line:
                continue
            fname, ftype = [x.strip() for x in line.split(':', 1)]
            fields.append((fname, ftype))
        structs.append((name, fields))
    return structs

def ser_field(ftype, expr, buf, lines):
    if ftype in TYPE_SIZES:
        sz = TYPE_SIZES[ftype]
        if ftype.startswith('i') or ftype.startswith('u'):
            # integer
            lines.append(f'\tv := {expr}')
            for i in range(sz):
                lines.append(f'\tappend({buf}, u8(v >> {i*8}))')
        elif ftype == 'f32':
            lines.append(f'\tbits := transmute(u32)({expr})')
            for i in range(4):
                lines.append(f'\tappend({buf}, u8(bits >> {i*8}))')
        elif ftype == 'f64':
            lines.append(f'\tbits := transmute(u64)({expr})')
            for i in range(8):
                lines.append(f'\tappend({buf}, u8(bits >> {i*8}))')
        elif ftype == 'bool':
            lines.append(f'\tif {expr} {{ append({buf}, u8(1)) }} else {{ append({buf}, u8(0)) }}')
    elif ftype in RL_FIELDS:
        for fname, fprim in RL_FIELDS[ftype]:
            if fprim == 'f32':
                lines.append(f'\tbits := transmute(u32)({expr}.{fname})')
                for j in range(4):
                    lines.append(f'\tappend({buf}, u8(bits >> {j*8}))')
            else:
                lines.append(f'\tappend({buf}, u8({expr}.{fname}))')
    else:
        raise ValueError(f"unsupported type {ftype}")

def deser_field(ftype, expr, data, off, lines):
    if ftype in TYPE_SIZES:
        sz = TYPE_SIZES[ftype]
        if ftype.startswith('i') or ftype.startswith('u'):
            lines.append(f'\t{expr} = {ftype}(0)')
            for i in range(sz):
                lines.append(f'\t{expr} |= {ftype}(data[off^+{i}]) << {i*8}')
            lines.append(f'\toff^ += {sz}')
        elif ftype == 'f32':
            lines.append(f'\t{expr} = transmute(f32)(u32(data[off^]) | (u32(data[off^+1]) << 8) | (u32(data[off^+2]) << 16) | (u32(data[off^+3]) << 24))')
            lines.append(f'\toff^ += 4')
        elif ftype == 'f64':
            lines.append(f'\tbits: u64 = 0')
            for i in range(8):
                lines.append(f'\tbits |= u64(data[off^+{i}]) << {i*8}')
            lines.append(f'\t{expr} = transmute(f64)bits')
            lines.append(f'\toff^ += 8')
        elif ftype == 'bool':
            lines.append(f'\t{expr} = data[off^] != 0')
            lines.append(f'\toff^ += 1')
    elif ftype in RL_FIELDS:
        for fname, fprim in RL_FIELDS[ftype]:
            if fprim == 'f32':
                lines.append(f'\t{expr}.{fname} = transmute(f32)(u32(data[off^]) | (u32(data[off^+1]) << 8) | (u32(data[off^+2]) << 16) | (u32(data[off^+3]) << 24))')
                lines.append(f'\toff^ += 4')
            else:
                lines.append(f'\t{expr}.{fname} = data[off^]')
                lines.append(f'\toff^ += 1')
    else:
        raise ValueError(f"unsupported type {ftype}")

def gen(name, fields):
    lname = name.lower()
    lines = []
    lines.append(f'// auto-generated by scripts/gen_replicated.py — do not edit by hand.')
    lines.append(f'serialize_{lname} :: proc(world: ^ecs.World, entity: ecs.Entity, buf: ^[dynamic]u8) -> int {{')
    lines.append(f'\tc, ok := ecs.try_get_component(world, entity, {name})')
    lines.append(f'\tif !ok {{ return 0 }}')
    lines.append(f'\tstart := len(buf^)')
    for fname, ftype in fields:
        expr = f'c.{fname}'
        ser_field(ftype, expr, 'buf', lines)
    lines.append(f'\treturn len(buf^) - start')
    lines.append('}')
    lines.append('')
    lines.append(f'deserialize_{lname} :: proc(world: ^ecs.World, entity: ecs.Entity, data: []u8, off: ^int) {{')
    lines.append(f'\tc, ok := ecs.try_get_component(world, entity, {name})')
    lines.append(f'\tif !ok {{')
    lines.append(f'\t\tecs.add_component(world, entity, {name}{{}})')
    lines.append(f'\t\tc, _ = ecs.try_get_component(world, entity, {name})')
    lines.append(f'\t}}')
    for fname, ftype in fields:
        expr = f'c.{fname}'
        deser_field(ftype, expr, 'data', 'off', lines)
    lines.append('}')
    lines.append('')
    return '\n'.join(lines)

def main():
    if len(sys.argv) < 2:
        print("usage: gen_replicated.py <input.odin> [output.odin]")
        sys.exit(1)
    inp = pathlib.Path(sys.argv[1])
    out = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else inp.with_name(inp.stem + "_replicated.odin")
    text = inp.read_text()
    structs = parse_structs(text)
    if not structs:
        print("no @replicated structs found")
        sys.exit(0)
    out_lines = ['package ' + inp.read_text().split('package ')[1].split()[0], '', 'import ecs "../src"', 'import net "../plugins/net"', '', '// auto-generated by scripts/gen_replicated.py', '']
    reg_lines = []
    for name, fields in structs:
        out_lines.append(gen(name, fields))
        lname = name.lower()
        reg_lines.append(f'\tnet.register_replicated(typeid_of({name}), serialize_{lname}, deserialize_{lname})')
    out_lines.append('register_replicated_components :: proc() {')
    out_lines.extend(reg_lines)
    out_lines.append('}')
    out_lines.append('')
    out.write_text('\n'.join(out_lines))
    print(f"wrote {out} ({len(structs)} structs)")

if __name__ == '__main__':
    main()
